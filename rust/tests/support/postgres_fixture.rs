//! Opt-in mutation fixture validation shared by Rust export replay tests.
use serde_json::Value;
use std::{
    io::Write,
    os::unix::fs::PermissionsExt,
    process::{Command, Stdio},
};

pub struct Fixture {
    pub url: String,
    container: String,
    pub schema: String,
}
impl Fixture {
    pub fn load() -> Option<Self> {
        let Ok(path) = std::env::var("DBCLI_TEST_POSTGRES_FIXTURE") else {
            eprintln!("SKIP export replay: set DBCLI_TEST_POSTGRES_FIXTURE to a marked disposable descriptor");
            return None;
        };
        assert_eq!(
            std::fs::metadata(&path).unwrap().permissions().mode() & 0o077,
            0
        );
        let data: Value = serde_json::from_slice(&std::fs::read(path).unwrap()).unwrap();
        assert_eq!(data["fixture_marker"], "dbcli-postgres-write-disposable-v1");
        assert_eq!(data["database"], "dbcli_postgres_write_fixture");
        let container = data["container"].as_str().unwrap().to_string();
        let output = Command::new("docker")
            .args(["inspect", &container])
            .output()
            .unwrap();
        assert!(output.status.success());
        let info: Value = serde_json::from_slice(&output.stdout).unwrap();
        assert_eq!(info[0]["Id"], data["container_id"]);
        assert_eq!(
            info[0]["Config"]["Labels"]["dbcli.fixture"],
            "postgres-write"
        );
        let port = data["port"].as_u64().unwrap();
        assert!(port > 0 && port != 5432);
        let bindings = info[0]["NetworkSettings"]["Ports"]["5432/tcp"]
            .as_array()
            .unwrap();
        assert!(bindings
            .iter()
            .any(|b| b["HostIp"] == "127.0.0.1" && b["HostPort"] == port.to_string()));
        let url = data["url"].as_str().unwrap().to_string();
        let (authority, database) = url
            .strip_prefix("postgresql://")
            .unwrap()
            .split_once('/')
            .unwrap();
        assert_eq!(
            authority.rsplit_once('@').unwrap().1,
            format!("127.0.0.1:{port}")
        );
        assert_eq!(
            database.split('?').next().unwrap(),
            "dbcli_postgres_write_fixture"
        );
        let schema = format!(
            "rust_export_{}_{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        );
        let fixture = Self {
            url,
            container,
            schema,
        };
        assert_eq!(
            fixture.sql("SELECT current_database()"),
            "dbcli_postgres_write_fixture"
        );
        fixture.sql(&format!("CREATE SCHEMA {}", fixture.schema));
        Some(fixture)
    }
    pub fn sql(&self, sql: &str) -> String {
        let mut child = Command::new("docker")
            .args([
                "exec",
                "-i",
                &self.container,
                "psql",
                "-X",
                "-qAt",
                "-v",
                "ON_ERROR_STOP=1",
                "-U",
                "dbcli_fixture",
                "-d",
                "dbcli_postgres_write_fixture",
            ])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .spawn()
            .unwrap();
        child
            .stdin
            .take()
            .unwrap()
            .write_all(sql.as_bytes())
            .unwrap();
        let output = child.wait_with_output().unwrap();
        assert!(
            output.status.success(),
            "Disposable PostgreSQL export replay failed (details suppressed)"
        );
        String::from_utf8(output.stdout).unwrap().trim().to_string()
    }
    pub fn populate(&self) -> String {
        let table = format!("{}.items", self.schema);
        self.sql(&format!("CREATE TABLE {table}(id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,base INTEGER,computed INTEGER GENERATED ALWAYS AS(base*2) STORED,other INTEGER GENERATED BY DEFAULT AS IDENTITY,label TEXT,payload JSONB);INSERT INTO {table}(id,base,other,label,payload) OVERRIDING SYSTEM VALUE VALUES(42,3,81,'it''s fine','null'),(43,4,82,'second',NULL);"));
        table
    }
}
impl Drop for Fixture {
    fn drop(&mut self) {
        // Only the unique schema created by this test is removed.
        if !std::thread::panicking() {
            self.sql(&format!("DROP SCHEMA {} CASCADE", self.schema));
        } else {
            let _ = std::panic::catch_unwind(|| {
                self.sql(&format!("DROP SCHEMA IF EXISTS {} CASCADE", self.schema))
            });
        }
    }
}
